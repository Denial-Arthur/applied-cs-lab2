# 1. Считывание данных из CSV
books = []
with open(FILENAME, 'r', encoding='utf-8') as f:
    reader = csv.reader(f, delimiter=';')
    header = next(reader)
    for row in reader:
        if row:
            books.append({
                'id': row[0],
                'author': row[1],
                'title': row[2],
                'year': int(row[3]),
                'price': float(row[4]),
                'downloads': int(row[5])
            })

